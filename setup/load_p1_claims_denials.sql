USE DATABASE HCLS_LAB;

CREATE SCHEMA IF NOT EXISTS P1_CLAIMS_DENIALS;
USE SCHEMA P1_CLAIMS_DENIALS;

-- Tables
CREATE OR REPLACE TABLE MEMBERS (
    MEMBER_ID VARCHAR(20), FIRST_NAME VARCHAR(50), LAST_NAME VARCHAR(50),
    DOB DATE, GENDER VARCHAR(1), STATE VARCHAR(2), ZIP VARCHAR(10),
    PLAN_ID VARCHAR(20), PLAN_TYPE VARCHAR(10), GROUP_NUMBER VARCHAR(20),
    PAYER_ID VARCHAR(20), EFFECTIVE_DATE DATE, TERM_DATE DATE
);

CREATE OR REPLACE TABLE PROVIDERS (
    PROVIDER_ID VARCHAR(20), PROVIDER_NPI VARCHAR(15),
    PROVIDER_NAME VARCHAR(100), SPECIALTY VARCHAR(50),
    FACILITY_NAME VARCHAR(100), STATE VARCHAR(2), NETWORK_STATUS VARCHAR(5)
);

CREATE OR REPLACE TABLE CLAIMS (
    CLAIM_ID VARCHAR(20), MEMBER_ID VARCHAR(20), PROVIDER_ID VARCHAR(20),
    PROVIDER_NPI VARCHAR(15), PROVIDER_NAME VARCHAR(100), FACILITY_NAME VARCHAR(100),
    PAYER_ID VARCHAR(20), DATE_OF_SERVICE DATE, CLAIM_TYPE VARCHAR(20),
    PLACE_OF_SERVICE VARCHAR(5), PRIMARY_DIAGNOSIS VARCHAR(10),
    DIAGNOSIS_DESCRIPTION VARCHAR(200), DIAGNOSIS_CATEGORY VARCHAR(50),
    CPT_CODE VARCHAR(10), CPT_DESCRIPTION VARCHAR(200),
    TOTAL_BILLED NUMBER(12,2), TOTAL_ALLOWED NUMBER(12,2), TOTAL_PAID NUMBER(12,2),
    STATUS VARCHAR(10), DENIAL_CODE VARCHAR(10), DENIAL_REASON VARCHAR(500),
    DENIAL_CATEGORY VARCHAR(50), IS_PREVENTABLE BOOLEAN
);

CREATE OR REPLACE TABLE DENIAL_NOTES (
    DENIAL_NOTE_ID VARCHAR(20), CLAIM_ID VARCHAR(20),
    NOTE_DATE DATE, DENIAL_CODE VARCHAR(10), NOTE_TEXT VARCHAR(16777216)
);

CREATE OR REPLACE TABLE PAYER_POLICIES (
    POLICY_ID VARCHAR(20), PAYER_ID VARCHAR(20),
    POLICY_TITLE VARCHAR(200), POLICY_TEXT VARCHAR(16777216)
);

-- Load from git repo
COPY INTO MEMBERS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p1_claims_denials/data/members.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO PROVIDERS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p1_claims_denials/data/providers.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO CLAIMS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p1_claims_denials/data/claims.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO DENIAL_NOTES FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p1_claims_denials/data/denial_notes.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO PAYER_POLICIES FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p1_claims_denials/data/payer_policies.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

-- Quick checks
SELECT 'MEMBERS' AS TBL, COUNT(*) AS ROWS FROM MEMBERS
UNION ALL SELECT 'PROVIDERS', COUNT(*) FROM PROVIDERS
UNION ALL SELECT 'CLAIMS', COUNT(*) FROM CLAIMS
UNION ALL SELECT 'DENIAL_NOTES', COUNT(*) FROM DENIAL_NOTES
UNION ALL SELECT 'PAYER_POLICIES', COUNT(*) FROM PAYER_POLICIES;
