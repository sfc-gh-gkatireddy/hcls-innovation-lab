USE DATABASE HCLS_LAB;

CREATE SCHEMA IF NOT EXISTS L2_PHARMACOVIGILANCE;
USE SCHEMA L2_PHARMACOVIGILANCE;

CREATE OR REPLACE TABLE PRODUCTS (
    PRODUCT_ID VARCHAR(20), PRODUCT_NAME VARCHAR(100),
    ACTIVE_INGREDIENT VARCHAR(100), THERAPEUTIC_AREA VARCHAR(50),
    DESCRIPTION VARCHAR(500)
);

CREATE OR REPLACE TABLE AE_CASES (
    CASE_ID VARCHAR(20), PRODUCT_ID VARCHAR(20), PRODUCT_NAME VARCHAR(100),
    ACTIVE_INGREDIENT VARCHAR(100), DRUG_ROLE VARCHAR(5),
    ROUTE_OF_ADMIN VARCHAR(20), REPORT_DATE DATE, EVENT_DATE DATE,
    PREFERRED_TERM VARCHAR(100), SOC VARCHAR(50),
    SERIOUSNESS VARCHAR(20), OUTCOME_CODE VARCHAR(5),
    OUTCOME_DESCRIPTION VARCHAR(50), PATIENT_AGE INT,
    PATIENT_SEX VARCHAR(1), REPORTER_TYPE VARCHAR(30),
    REPORTER_COUNTRY VARCHAR(5), REPORT_QUARTER VARCHAR(10)
);

CREATE OR REPLACE TABLE CASE_NARRATIVES (
    CASE_ID VARCHAR(20), NARRATIVE_TYPE VARCHAR(20),
    NARRATIVE_TEXT VARCHAR(16777216)
);

COPY INTO PRODUCTS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l2_pharmacovigilance/data/products.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO AE_CASES FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l2_pharmacovigilance/data/ae_cases.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO CASE_NARRATIVES FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l2_pharmacovigilance/data/case_narratives.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

SELECT 'PRODUCTS' AS TBL, COUNT(*) AS ROWS FROM PRODUCTS
UNION ALL SELECT 'AE_CASES', COUNT(*) FROM AE_CASES
UNION ALL SELECT 'CASE_NARRATIVES', COUNT(*) FROM CASE_NARRATIVES;
