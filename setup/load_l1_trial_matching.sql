-- ============================================================
-- L1: Clinical Trial Patient/Site Matching — Load from Git Repo
-- Prerequisite: run setup/00_common.sql first
-- ============================================================
USE DATABASE HCLS_LAB;

CREATE SCHEMA IF NOT EXISTS L1_TRIAL_MATCHING;
USE SCHEMA L1_TRIAL_MATCHING;

CREATE OR REPLACE TABLE PATIENTS (
    PATIENT_ID VARCHAR(20), SITE_ID VARCHAR(20), AGE INT,
    SEX VARCHAR(1), RACE VARCHAR(20), COUNTRY VARCHAR(5)
);

CREATE OR REPLACE TABLE DIAGNOSES (
    PATIENT_ID VARCHAR(20), DIAGNOSIS_CODE VARCHAR(10),
    DIAGNOSIS_DESCRIPTION VARCHAR(200), DIAGNOSIS_DATE DATE, STATUS VARCHAR(10)
);

CREATE OR REPLACE TABLE LABS (
    PATIENT_ID VARCHAR(20), LAB_CODE VARCHAR(20), LAB_NAME VARCHAR(100),
    VALUE NUMBER(10,2), UNIT VARCHAR(30), LAB_DATE DATE,
    NORMAL_LOW NUMBER(10,2), NORMAL_HIGH NUMBER(10,2)
);

CREATE OR REPLACE TABLE MEDICATIONS (
    PATIENT_ID VARCHAR(20), MEDICATION_NAME VARCHAR(100),
    MEDICATION_CLASS VARCHAR(50), ROUTE VARCHAR(20),
    FREQUENCY VARCHAR(10), STATUS VARCHAR(10), START_DATE DATE
);

CREATE OR REPLACE TABLE SITES (
    SITE_ID VARCHAR(20), SITE_NAME VARCHAR(100), CITY VARCHAR(50),
    STATE VARCHAR(5), COUNTRY VARCHAR(5), ANNUAL_PATIENT_VOLUME INT
);

-- Internal stage for the protocol document
CREATE OR REPLACE STAGE L1_DOCS;

COPY INTO PATIENTS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l1_trial_matching/data/patients.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO DIAGNOSES FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l1_trial_matching/data/diagnoses.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO LABS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l1_trial_matching/data/labs.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO MEDICATIONS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l1_trial_matching/data/medications.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO SITES FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l1_trial_matching/data/sites.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

-- Copy the protocol document to the internal stage for AI_PARSE_DOCUMENT
COPY FILES
  INTO @L1_DOCS
  FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/l1_trial_matching/docs/;

SELECT 'PATIENTS' AS TBL, COUNT(*) AS ROWS FROM PATIENTS
UNION ALL SELECT 'DIAGNOSES', COUNT(*) FROM DIAGNOSES
UNION ALL SELECT 'LABS', COUNT(*) FROM LABS
UNION ALL SELECT 'MEDICATIONS', COUNT(*) FROM MEDICATIONS
UNION ALL SELECT 'SITES', COUNT(*) FROM SITES;

-- Verify protocol is staged
LIST @L1_DOCS;
