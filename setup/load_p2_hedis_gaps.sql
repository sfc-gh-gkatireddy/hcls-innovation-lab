USE DATABASE HCLS_LAB;

CREATE SCHEMA IF NOT EXISTS P2_HEDIS_GAPS;
USE SCHEMA P2_HEDIS_GAPS;

CREATE OR REPLACE TABLE MEMBERS (
    MEMBER_ID VARCHAR(20), FIRST_NAME VARCHAR(50), LAST_NAME VARCHAR(50),
    DOB DATE, AGE INT, SEX VARCHAR(1), STATE VARCHAR(2),
    PLAN_TYPE VARCHAR(30), PCP_PROVIDER VARCHAR(100), RISK_SCORE NUMBER(4,2)
);

CREATE OR REPLACE TABLE MEASURE_GAPS (
    GAP_ID VARCHAR(20), MEMBER_ID VARCHAR(20), MEASURE_ID VARCHAR(20),
    MEASURE_NAME VARCHAR(200), CATEGORY VARCHAR(50), MEASUREMENT_YEAR INT,
    GAP_STATUS VARCHAR(10), CLOSED_BY VARCHAR(20), EVIDENCE_IN_NOTES BOOLEAN
);

CREATE OR REPLACE TABLE CLAIMS (
    CLAIM_ID VARCHAR(20), MEMBER_ID VARCHAR(20), DATE_OF_SERVICE DATE,
    DIAGNOSIS_CODE VARCHAR(10), DIAGNOSIS_DESCRIPTION VARCHAR(200),
    CPT_CODE VARCHAR(10), CPT_DESCRIPTION VARCHAR(200),
    PROVIDER VARCHAR(100), BILLED_AMOUNT NUMBER(12,2), PAID_AMOUNT NUMBER(12,2)
);

CREATE OR REPLACE TABLE VISIT_NOTES (
    NOTE_ID VARCHAR(20), MEMBER_ID VARCHAR(20), VISIT_DATE DATE,
    PROVIDER VARCHAR(100), NOTE_TYPE VARCHAR(30),
    NOTE_TEXT VARCHAR(16777216)
);

COPY INTO MEMBERS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p2_hedis_gaps/data/members.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO MEASURE_GAPS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p2_hedis_gaps/data/measure_gaps.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO CLAIMS FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p2_hedis_gaps/data/claims.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

COPY INTO VISIT_NOTES FROM @HCLS_LAB.PUBLIC.HCLS_LAB_REPO/branches/main/tracks/p2_hedis_gaps/data/visit_notes.csv
  FILE_FORMAT = HCLS_LAB.PUBLIC.CSV_FORMAT;

SELECT 'MEMBERS' AS TBL, COUNT(*) AS ROWS FROM MEMBERS
UNION ALL SELECT 'MEASURE_GAPS', COUNT(*) FROM MEASURE_GAPS
UNION ALL SELECT 'CLAIMS', COUNT(*) FROM CLAIMS
UNION ALL SELECT 'VISIT_NOTES', COUNT(*) FROM VISIT_NOTES;
